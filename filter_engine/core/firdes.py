"""Tap generators and order estimators that scipy does not provide.

The pulse-shaping responses (RRC, RC, Gaussian) are the ones an SDR user
reaches for constantly but ``scipy.signal`` has no direct equivalent of, so
they are implemented here from their closed-form impulse responses.  The
naming deliberately mirrors GNU Radio's ``gr::filter::firdes`` so that code
generated by this tool reads the same way as hand-written GNU Radio code.

Order estimation lives here too: ``firwin``/``remez``/``firls`` all take a tap
count rather than a tolerance, so something has to turn "60 dB stopband over a
25 kHz transition" into a number of taps.
"""

from __future__ import annotations

import math

import numpy as np
from scipy import signal

#: Approximate stopband attenuation a windowed (``firwin``) design can reach
#: with each window, in dB.  This is set by the window's peak sidelobe and is
#: a *hard ceiling*: adding taps narrows the transition but does not push the
#: stopband any deeper.  It is the single most common surprise in windowed
#: FIR design, so the designer warns about it explicitly.
WINDOW_MAX_ATTEN_DB: dict[str, float] = {
    "boxcar": 21.0,
    "bartlett": 26.0,
    "hann": 44.0,
    "hamming": 53.0,
    "blackman": 74.0,
    "flattop": 85.0,
    "blackmanharris": 92.0,
    "nuttall": 98.0,
}


#: Approximate transition-width constant ``K`` for each window, such that
#: ``num_taps ~= K * sample_rate / transition_width``.  It comes from the
#: window's main-lobe width (Oppenheim & Schafer's table, extended to the
#: multi-term windows), and it is what actually sets the length -- a Blackman
#: window needs roughly 1.7x the taps of a Hamming to hit the same transition
#: because its main lobe is that much wider.
WINDOW_TRANSITION_K: dict[str, float] = {
    "boxcar": 0.905,
    "bartlett": 3.05,
    "hann": 3.10,
    "hamming": 3.30,
    "blackman": 5.50,
    "blackmanharris": 7.60,
    "nuttall": 8.00,
    "flattop": 9.00,
}


def window_atten_limit(window: str) -> float | None:
    """Stopband ceiling for ``window``, or ``None`` if it has no fixed ceiling.

    Kaiser is the exception: its beta parameter trades sidelobe level against
    transition width, so it can hit any attenuation you ask for.
    """
    return WINDOW_MAX_ATTEN_DB.get(window)


def suggest_window(stopband_atten_db: float) -> str:
    """Cheapest fixed window that can reach ``stopband_atten_db``."""
    for name, limit in sorted(WINDOW_MAX_ATTEN_DB.items(), key=lambda kv: kv[1]):
        if limit >= stopband_atten_db:
            return name
    return "kaiser"


